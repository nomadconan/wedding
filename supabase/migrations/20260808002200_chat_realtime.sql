-- 0021 이 "publication 은 지금 열지 않는다 — 결정은 결정한 자리에 남아야 한다" 고
-- 남겼다. 그 자리가 여기다.
--
-- ── O-11 결정 — **Supabase Realtime 을 쓴다** ────────────────────────────────
-- 근거는 넷이다.
--
--  1. **Vercel 에는 상주 프로세스가 없다.** 별도 웹소켓 서버를 두려면 Vercel 밖에
--     런타임을 하나 더 세우고(Fly·Railway 등) 배포·스케일·비밀키 관리를 두 벌로
--     끌고 가야 한다. 기능 하나를 위해 인프라 축을 하나 더 여는 셈이다.
--     SSE 로 우회하는 길도 서버리스 함수의 최대 실행 시간에 묶여 대화 화면이
--     주기적으로 끊긴다 — 끊기는 실시간은 폴링보다 나을 것이 없다.
--
--  2. **RLS 정합이 결정적이다.** Realtime 의 postgres_changes 는 구독자마다 그
--     사람의 JWT 로 RLS 를 다시 평가한다. 즉 0021 이 만든 `is_chat_room_member()`
--     **그 경계가 그대로 전송 계층의 경계가 된다.**
--     별도 웹소켓 서버는 방 참여 판정을 애플리케이션 코드로 다시 구현해야 하고,
--     그 순간 경계가 둘이 된다 — CLAUDE.md §5.5 가 "앱 레벨 권한 체크는 보안
--     경계가 아니다" 라고 못박은 바로 그 상태다.
--
--  3. **이 채팅이 전송 계층에 요구하는 양이 적다.** 읽음은 메시지마다가 아니라
--     방을 열 때 `chat_room_reads` 한 행 upsert 이고(0021), 첨부는 서명 URL 로
--     Storage 에 직접 오가므로 소켓을 타지 않으며, 알림은 S4-13 의 발송 경로를
--     쓴다. 소켓이 나르는 것은 "방에 무슨 일이 있었다" 는 신호 하나뿐이다.
--
--  4. **운영 비용이 0 이다.** Realtime 은 로컬·스테이징·운영 어디에나 이미 떠
--     있고, `@supabase/realtime-js` 는 `@supabase/supabase-js` 의 의존성이라
--     **새 npm 패키지가 없다.**
--
-- ── 무엇을 publication 에 넣는가 — `chat_rooms` 하나다 ──────────────────────
-- `chat_messages` 가 아니다. 이유가 설계의 핵심이다.
--
--  · postgres_changes 는 **바뀐 행 전체를 payload 로 보낸다.** `chat_messages` 를
--    넣으면 **본문과 첨부 목록이 소켓을 타고 나간다.** 받는 사람이 그 방의
--    참여자라 해도, 본문을 굳이 전송 계층에 흘릴 이유가 없다.
--  · 더 중요한 것은 **회수(retracted)** 다. 0021 은 회수된 메시지의 본문을
--    `chat_messages_visible` 뷰로 가린다. postgres_changes 는 뷰를 거치지 않고
--    표에서 바로 나오므로, 메시지를 구독하면 **뷰가 세운 가림막을 소켓이 우회**한다.
--  · `chat_rooms` 는 그럴 위험이 없다. 그리고 0021 의 `chat_room_touch()` 트리거가
--    메시지가 들어올 때마다 `last_message_at` 을 갱신하므로, **방을 구독하는 것만으로
--    "새 메시지가 왔다" 는 신호가 그대로 온다.** 담당자 배정·SLA 시계 변화도 같은
--    구독으로 업체 인박스에 실시간 반영된다.
--
-- 그래서 클라이언트 규칙은 하나다 — **소켓은 신호이고, 진실은 다시 조회한다.**
-- 신호를 받으면 `/api/chat/messages` 를 다시 부르고, 그 API 는 언제나
-- `chat_messages_visible` 뷰를 읽는다. 소켓이 끊긴 환경에서는 같은 조회를 주기적으로
-- 하면 되므로 폴백이 동작상 동일하다.
--
-- replica identity 는 기본(PK) 그대로 둔다. `old_record` 가 필요 없고, 기본값으로도
-- UPDATE 의 **새 행**은 온전히 전달된다. `full` 로 올리면 WAL 만 커진다.
-- =============================================================================

alter publication supabase_realtime add table public.chat_rooms;

comment on table public.chat_rooms is
  '고객-업체 1:1 대화방(F-C-27·F-V-15). 커플 양측이 같은 방을 공유하고, 업체 측은 owner·staff 여럿이 같은 방에 들어온다 — 방은 조직 단위 1:1 이다. **supabase_realtime publication 대상**(S4-04·O-11): 메시지가 들어오면 chat_room_touch() 가 last_message_at 을 갱신하므로 이 표만 구독해도 새 메시지 신호가 온다. chat_messages 는 넣지 않는다 — 본문이 소켓을 타고, 회수 가림막(chat_messages_visible)을 우회하기 때문이다.';

-- =============================================================================
-- 응답 SLA 기준 시간 (§2.2 F-V-15, §7.4 가변 파라미터 원칙)
-- -----------------------------------------------------------------------------
-- **코드에 박지 않는다.** 운영이 화면 배포 없이 바꿀 값이다.
-- 0021 이 만든 `chat_rooms.awaiting_vendor_since` 가 시계이고, 이 행이 눈금이다.
--
--   minutes     — 이 시간을 넘기면 '지연'(overdue). 초기 운영값 24시간.
--   warnPercent — 눈금의 몇 %에서 '임박'(due)으로 볼 것인가. 초기값 75%.
--
-- 초기값을 여기 넣는 이유: 값이 없으면 화면이 SLA 를 아예 못 그리는데, 그것은
-- "기준이 없다" 가 아니라 **기능이 없는 것**이다. `lib/core/pricing/rates.ts` 가
-- "전역 기본값조차 코드가 아니라 DB 에서" 라고 쓴 원칙을 그대로 따른다 — 값의 자리는
-- DB 이고, 코드는 행이 사라졌을 때 SLA 표시를 끄기만 한다(숫자를 지어내지 않는다).
-- 이 값은 O-번호가 걸린 미결 사항이 아니라 **운영 파라미터**다(수수료 요율 O-02 와
-- 다르다) — 그래서 초기값을 두는 것이 임의 확정이 아니다.
-- =============================================================================
insert into public.app_settings (key, value_json, description)
values (
  'chat.sla_response_minutes',
  '{"minutes": 1440, "warnPercent": 75}'::jsonb,
  '업체 채팅 응답 SLA(F-V-15). minutes 를 넘기면 지연, warnPercent 지점부터 임박으로 본다. 운영 파라미터이므로 배포 없이 바꾼다.'
)
on conflict (key) do nothing;

