-- **표를 만들지 않는다. 행 하나다.**
--
-- F-C-37 은 **완료 조건에 실효 판정을 포함하는 유일한 화면**이다(§7.5). 보기 전용
-- 화면은 만들기는 쉽고 가치를 증명하기는 어렵다 — 사용자는 이미 캘린더 앱을 쓰고
-- 있고, 우리 화면이 더 나은 이유가 "예쁘다" 뿐이면 두 번째 방문이 없다.
--
-- §7.5 는 그 결론을 **"못 주는 표현은 삭제가 아니라 `feature_flags` 로 끈다"** 로
-- 적었다(D-09·D-20 — 기능을 빼지 않고 만들어 두고 켜지 않는다). 그러려면 **끄는
-- 자리가 실제로 있어야** 한다. 이 파일이 그 자리를 만든다.
--
-- 판단이 필요했던 지점과 근거
--
--  1. **지금 넷 다 켠다.** 판정은 지표가 붙는 S8-01 이후이고(O-16) 여기서 미리 끄면
--     그것이 판정을 앞지른 셈이 된다 — D-66 이 어뷰징 임계값에서 세운 규칙과 같다
--     ("지금 정하면 그것이 운영 기준처럼 굳는다"). 스위치를 만드는 일과 스위치를
--     내리는 일은 다른 일이다.
--
--  2. **키를 넷으로 쪼개지 않는다.** `schedule.timeline`·`schedule.progress`… 로 두면
--     한 기능의 개폐가 네 행에 흩어지고 그 중 하나만 고치는 날이 온다. 표현은 한
--     화면의 토글이므로 **행 하나 + `rollout_json`** 이 맞다(0041 이 커뮤니티 개방
--     조건을 `rollout_json` 에 적어 둔 것과 같은 자리다 · D-67).
--
--  3. **`enabled` 는 참이다.** 이 플래그가 묻는 것은 "화면을 여는가" 가 아니라
--     "어느 표현을 보이는가" 다 — `/checklist` 자체는 S7-08 이 이미 열었고 커뮤니티와
--     달리 여는 조건이 미충족인 상태가 아니다. `enabled=false` 로 두면 화면이 통째로
--     닫힌 것처럼 읽히고, 그것은 이 행이 말하려는 바가 아니다.
--
--  4. **행이 없을 때를 '켜짐' 으로 읽는다**(`lib/core/schedule/view.ts`). 커뮤니티는
--     반대였다 — 그쪽은 **여는 조건이 미충족**이라 없는 행을 꺼짐으로 읽는 것이 방어였고
--     (D-49 와 같은 규칙), 이쪽은 **조건이 없고 판정만 남았다.** 없는 행을 꺼짐으로
--     읽으면 마이그레이션이 안 돈 환경에서 화면이 비는데, 그것은 방어가 아니라 사고다.
-- =============================================================================

insert into public.feature_flags (key, enabled, rollout_json)
values (
  'schedule.views',
  true,
  jsonb_build_object(
    'timeline', true,
    'progress', true,
    'next',     true,
    'graph',    true,
    -- 다음 사람이 **무엇을 근거로 끄는지** 알 수 있게 판정 계획을 행에 적어 둔다
    -- (0041 이 커뮤니티 개방 조건을 적어 둔 것과 같은 이유다 · D-67).
    'decided_by', 'O-16',
    'measure_after', 'S8-01',
    'metrics', jsonb_build_array(
      '뷰 전환율 — 기본(A) 말고 다른 표현을 실제로 여는가',
      '의존 관계 뷰(D) 체류 시간',
      '선행 관계가 있는 태스크의 완료율이 없는 태스크보다 높은가',
      '순서 안내를 본 뒤 태스크가 실제로 생성되는가'
    )
  )
)
on conflict (key) do nothing;

comment on table public.feature_flags is
  '공개 시점 제어의 유일한 수단(CLAUDE.md §2.1). 기능 범위 축소로 대체하지 않는다. rollout_json 은 켬/끔이 아니라 **어느 부분을 켜는가**를 담는다 — community.enabled 는 개방 조건을, schedule.views 는 표현 넷의 스위치와 판정 계획을 담고 있다.';

