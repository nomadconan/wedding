-- 0023 · 알림 토픽에 `chat` 추가 (S4-04)
-- 근거: docs/07_개발명세서.md §2.1 F-C-21·F-C-27, §3.7 notifications, D-23
-- =============================================================================
-- S4-04 가 새 메시지 알림을 붙이면서 토픽이 하나 늘었다. `notifications.topic` 은
-- text + CHECK 라(0001 원칙: 명세가 값 집합을 명시한 컬럼만 ENUM) 값 집합을 넓히려면
-- 제약을 바꿔야 한다.
--
-- **드롭 후 재생성한다.** 기존 마이그레이션(0004)을 고치지 않고 새 파일로만 더한다는
-- 규칙(CLAUDE.md §7.2)을 지키면서 값 집합을 넓히는 방법은 이것뿐이다. 데이터는 건드리지
-- 않으며, 기존 6개 값은 그대로 통과한다.
--
-- ── 왜 채팅 알림을 붙였는가 ─────────────────────────────────────────────────
-- 실시간(Realtime)은 **화면을 켜 둔 사람**에게만 닿는다. 대화는 상대가 보고 있지 않을
-- 때가 대부분이고, 분쟁에서 쟁점이 되는 것도 정확히 그 경우다 — "연락을 받았는가"
-- (D-23). 알림이 없으면 업체 응답 SLA(F-V-15)가 "업체가 화면을 켜 두었는가" 에
-- 좌우되는데, 그건 SLA 가 아니다.
--
-- ── 값 집합이 두 곳에 있다는 사실 ───────────────────────────────────────────
-- 토픽 목록은 `lib/core/schemas/notification.ts` 의 `NOTIFICATION_TOPICS` 와 이 CHECK
-- 두 곳에 있다. S4-04 에서 TS 쪽만 늘렸다가 발송이 조용히 실패했다 — 알림은 실패해도
-- 본 작업을 되돌리지 않게 만들어 두었기 때문에(의도한 설계) 더 조용했다.
-- 토픽을 더할 때는 **반드시 두 곳을 함께** 고친다. `db:rls` 에 두 목록이 어긋나면
-- 걸리는 검사를 넣어 두었다.
-- =============================================================================

alter table public.notifications drop constraint if exists notifications_topic_chk;

alter table public.notifications
  add constraint notifications_topic_chk
  check (
    topic in (
      'dday',
      'schedule',
      'contract',
      'care',
      'price_change',
      'couple_invite',
      -- S4-04. 업체 채팅 새 메시지(F-C-27). 본문은 담지 않고 방 id 만 참조한다(§7.3).
      'chat'
    )
  );

comment on column public.notifications.topic is
  '알림 토픽. 값 집합은 notifications_topic_chk 와 lib/core/schemas/notification.ts 의 NOTIFICATION_TOPICS **양쪽**이 갖는다 — 더할 때 둘을 함께 고친다(0023 주석 참조).';

