-- =============================================================================
-- 0078 · 상품 컨셉 태그 (C-2d)
--   근거: 07 §2.1 F-C-10 확장 · §3.3 「C 단계가 상품 쪽에 더하는 칸」 · B-1 §1-2
--
-- ── 무엇이 없었나 ───────────────────────────────────────────────────────────
-- 태그가 **업체에만** 붙는다(0017). 한 스튜디오가 '로맨틱 패키지' 와 '미니멀
-- 패키지' 를 함께 팔면 **둘을 가를 자리가 없다**(B-1 §1-2).
--
-- ── 어휘를 늘리지 않는다 ────────────────────────────────────────────────────
-- 값 집합은 `vendors.style_tags`·`couples.style_tags` 와 **같은 STYLE_TAGS 8종**이고
-- CHECK 도 **0017 과 같은 모양**이다. 늘리면 세 표의 어휘가 갈라지고, 그러면
-- "커플이 고른 로맨틱" 과 "상품에 적힌 로맨틱" 이 다른 값이 되어 매칭이 성립하지
-- 않는다(0017 이 업체 어휘를 따로 두지 않은 것과 같은 이유). **C-2a 가 카테고리
-- 어휘를 막 정리한 직후**라 여기서 새 어휘를 만들 이유가 더욱 없다.
--
-- ── 카테고리 축과 **다른 축**이다 ───────────────────────────────────────────
-- C-2a 가 만든 것은 *파는 축*(hall·studio…)과 *준비 축*(sdm·honeymoon…)이고
-- 그 둘은 **매핑으로 이어져 있다**(D-206). 컨셉 태그는 그 둘 **어디에도 속하지
-- 않는다** — '로맨틱' 은 무엇을 파는가도 무엇을 준비하는가도 아니고 **어떤 느낌인가**다.
-- 그래서 `lib/core/category/axes.ts` 에 넣지 않고 `lib/core/product/concept.ts` 에
-- 따로 뒀다. 섞으면 매핑 표가 "느낌 → 카테고리" 라는 없는 대응을 갖게 된다.
--
-- ── 기본값을 빈 배열로 두는 이유 ────────────────────────────────────────────
-- 업체 태그를 **복사해 넣지 않는다.** 복사하면 그 순간부터 두 벌이 되고, 업체가
-- 태그를 바꿔도 상품은 옛 값을 들고 있는다 — **계산 가능한 값을 저장하는 일**이다.
-- 대신 **읽을 때 상속**한다: 상품에 태그가 있으면 그것이 답이고, 없으면 업체 태그를
-- 쓴다(`effectiveStyleTags`). 그래서 **기존 상품이 필터에서 사라지지 않는다** —
-- 지금 모든 상품의 태그가 비어 있고, 전부 업체 태그로 계속 걸린다.
-- =============================================================================

alter table public.products
  add column if not exists style_tags text[] not null default '{}';

comment on column public.products.style_tags is
  '상품 컨셉(C-2d · F-C-10 필터). 어휘는 vendors.style_tags·couples.style_tags 와 '
  '**같은 STYLE_TAGS 8종**이다. **비어 있으면 업체 태그를 상속한다** — 값을 복사해 '
  '두지 않고 읽을 때 정한다(lib/core/product/concept.ts). 카테고리 두 축(D-206)과는 '
  '다른 축이며 서로 매핑하지 않는다.';

-- 값 집합을 못박는다. **오타 한 번이면 그 상품은 어떤 필터에도 안 걸리고**
-- 아무도 그 사실을 눈치채지 못한다(0017 이 업체에서 겪지 않으려고 건 것과 같다).
alter table public.products
  add constraint products_style_tags_chk
  check (
    style_tags <@ array[
      'modern', 'classic', 'natural', 'romantic',
      'minimal', 'luxury', 'outdoor', 'small_wedding'
    ]::text[]
  );

-- 탐색 필터는 배열 겹침(&&)으로 판정한다. GIN 이 그 연산자를 받는다 —
-- 업체 쪽 `idx_vendors_style_tags` 와 같은 이유·같은 모양이다.
create index if not exists idx_products_style_tags
  on public.products using gin (style_tags);

-- =============================================================================
-- RLS 는 손대지 않는다 (§3.9)
--   `products` 정책 그대로다 — 게시분은 anon 이 읽고(status='published' + 업체
--   active), **쓰기는 owner 전용**이다. 태그는 `products` 의 칸이라 "남의 상품에
--   태그를 붙이는" 경로가 애초에 없다(C-2b 의 `vendor_media` 와 다른 점이다 —
--   그쪽은 자기 업체의 행에서 남의 상품을 가리킬 수 있어 복합 FK 가 필요했다).
--   그 사실을 `db:rls` 가 눌러서 확인한다.
--
--   컬럼 권한도 그대로다 — `authenticated` 의 products UPDATE 는 **표 단위**라
--   새 칸이 자동으로 같은 규칙을 받는다. 칸마다 걷은 표였다면 여기서 다시 걷어야 했다.
-- =============================================================================

