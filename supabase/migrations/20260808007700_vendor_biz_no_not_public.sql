-- =============================================================================
-- 0077 사업자번호 해시를 공개 카탈로그에서 걷는다 (C-2c 발견 · FIX-79)
--   명세서 §7.2 · §3.9 · CLAUDE.md §5.4·§5.5
--
-- ── 무엇이 새고 있었나 ───────────────────────────────────────────────────────
-- `vendors` 는 공개 카탈로그라 anon SELECT 가 열려 있다(§3.9). 그런데 그것이
-- **표 단위 GRANT** 여서 `biz_no_enc` 까지 함께 나갔다 — 비로그인이 활성 업체
-- 전부의 사업자번호 해시를 읽을 수 있었다.
--
-- ── 왜 해시인데도 문제인가 ───────────────────────────────────────────────────
-- 사업자등록번호는 **10자리이고 검증숫자가 있다.** 후보가 10^9 규모라 소금 없는
-- SHA-256 은 **전수 대입으로 몇 초면 되돌아간다**(`app/api/vendor/apply/route.ts`
-- 가 `createHash("sha256").update(businessNumber)` 로 만든다). 즉 §7.2 가
-- *"평문으로 저장하지 않는다"* 로 지키려던 것이 **공개 읽기 한 줄로 무효**였다.
--
-- **이 리포는 이미 같은 판단을 한 적이 있다** — `ipHash()` 가 *"소금 없이 해시하면
-- IPv4 는 전수 대입으로 되돌릴 수 있으므로 앱 비밀을 소금으로 쓴다"* 고 적고
-- 소금이 없으면 아예 해시를 만들지 않는다. 같은 규칙이 여기는 안 걸려 있었다.
--
-- ── 왜 칸만 걷지 않고 표에서 걷는가 (§5.5 층 1) ──────────────────────────────
-- `revoke select (biz_no_enc)` 만 하면 **표 단위 GRANT 가 남아 무효**다.
-- 표에서 걷고 **남길 칸을 나열해 다시 준다.** `authenticated` 의 UPDATE 가 이미
-- 그 모양이다(0050 · FIX-30 이 `status`·`badge_flags` 를 같은 방법으로 걷었다).
--
-- ── 소금을 치지 않는 이유 ────────────────────────────────────────────────────
-- 소금을 더하면 **기존 행을 다시 만들 수 없다**(원문이 없다 — 그것이 요점이다).
-- 지금 필요한 것은 "이 값이 밖으로 나가지 않는 것" 이고 그것은 권한으로 끝난다.
-- 소금·HMAC 로 바꾸는 일은 원문을 다시 받는 절차(재심사)와 함께 서야 한다.
-- =============================================================================

-- 표에서 걷는다. **칸만 걷으면 무효다.**
revoke select on public.vendors from anon, authenticated;

-- 남길 칸을 나열해 다시 준다 — `biz_no_enc` 하나만 빠진다.
-- (§3.9 가 공개로 정한 카탈로그 칸들이며 화면·탐색이 그대로 쓴다.)
grant select (
  id, name, category, region_code, status, badge_flags,
  created_at, updated_at, address, address_detail,
  capacity_min, capacity_max, facilities, intro, style_tags
) on public.vendors to anon, authenticated;

-- `service_role` 과 `postgres` 는 건드리지 않는다 — 입점 신청(서비스롤)이 이 칸에
-- 쓰고, 운영자 심사가 대조한다. 그쪽은 서버 전용이라 클라이언트로 나가지 않는다.

comment on column public.vendors.biz_no_enc is
  '사업자번호 SHA-256 해시. 평문 저장 금지(§7.2). **anon·authenticated 에게 주지 않는다** '
  '— 10자리 숫자의 소금 없는 해시는 전수 대입으로 되돌아간다(FIX-79 · 0077). '
  '표시용은 vendor_applications.biz_no_masked 이며 그 표는 심사 당사자만 읽는다.';

-- =============================================================================
-- 이 파일이 한 것
--   REVOKE vendors 표 단위 SELECT (anon, authenticated)
--   GRANT  vendors 칸 15개 SELECT 재부여 — biz_no_enc 제외
--   새 표·컬럼·정책 없음. RLS 정책은 그대로다(어느 **행**이 보이는가는 안 바뀌고
--   어느 **칸**이 보이는가만 좁아진다).
-- =============================================================================
