-- 0039 · 커뮤니티 공개 플래그 (S7-15)
-- 근거: CLAUDE.md §2.1(공개 시점 제어는 feature_flags 로만), docs/07 §3.8,
--       T-00f "모더레이션이 없으면 커뮤니티를 열 수 없다"
-- =============================================================================
-- S7-15 가 소비자 게시판을 만들었다. 신고 **버튼**은 여기 있고 처리 **큐**는 S7-17 에
-- 있다 — 그 사이에는 신고를 받고도 처리 경로가 없는 상태가 존재한다.
--
-- **기능을 나중으로 미루지 않는다.** 그것은 범위 축소이며 CLAUDE.md §2.1 이 금지한다.
-- 대신 **만들어 두고 켜지 않는다** — 화면·API 는 완성돼 있고 플래그가 꺼져 있어
-- `/community` 는 404 로 답한다. S7-17 이 큐를 세우면 이 행의 `enabled` 를 true 로
-- 바꾸는 것으로 열린다(코드 변경 없음).
--
-- `feature_flags` 의 **첫 사용처**다. 표는 T-03(0004)이 만들었고 지금까지 소비자가
-- 없었다 — 그래서 "만들어 두고 켜지 않는다" 가 문서에만 있던 규칙이었다.
-- =============================================================================
insert into public.feature_flags (key, enabled, rollout_json)
values (
  'community.enabled',
  false,
  '{"reason": "모더레이션 큐(S7-17) 완료 후 개방", "owner": "S7-17"}'::jsonb
)
on conflict (key) do nothing;

comment on table public.feature_flags is
  '공개 시점 제어의 유일한 수단(CLAUDE.md §2.1). 기능 범위 축소로 대체하지 않는다. 첫 사용처는 community.enabled(S7-15) — 화면은 완성돼 있고 스위치만 꺼져 있다.';
