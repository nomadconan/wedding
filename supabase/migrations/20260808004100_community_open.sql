       rollout_json = jsonb_build_object(
         'reason', '세 층(필터·모더레이션·라벨링)과 양측 절차가 모두 갖춰짐',
         'opened_by', 'S7-16',
         'done', jsonb_build_array(
           'S7-14 스키마',
           'S7-15 소비자 화면·신고',
           'S7-16 업체 답변·신고',
           'S7-17 모더레이션 큐'
         )
       )
