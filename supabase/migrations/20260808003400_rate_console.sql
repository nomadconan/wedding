-- =============================================================================
-- 0034 · 요율 관리 콘솔 (S5-03)
-- 근거: docs/07_개발명세서.md §2.3 F-A-15, §3.8 commission_rates·planner_fee_rates,
--       §3.9 RLS, §4.3 CRUD /api/admin/commission-rates, §6.4 /admin/commission-rates,
--       D-16 · D-17 · D-23, O-02
-- =============================================================================
-- 0006 이 요율 두 표를 만들면서 **SELECT 정책만** 주고 갔다. 그 정책은 업체 멤버와
-- 플래너를 위한 것이라 **운영자에게는 요율이 보이지 않는다** — F-A-15 화면이 자기
-- 목록조차 그릴 수 없는 상태였다. 그리고 쓰기 정책은 어느 역할에도 없다.
--
-- 명세는 F-A-15 를 **"개발 블로커 해제 장치"** 라고 적었다(§부록). 요율 **값**이
-- 미확정이어도(O-02) 값을 넣는 화면이 있으면 거래·정산 개발이 값에 묶이지 않는다는
-- 뜻이다. 그런데 지금 `commission_rates` 는 **0행**이고, 그래서 계약 발행이
-- `CONTRACT_RATE_UNRESOLVED`(S5-06)로 막혀 **결제·정산·해지 전체 흐름이 로컬에서
-- 한 번도 끝까지 돌지 않았다.** 이 파일이 그 자물쇠를 연다.
--
-- 이 파일이 정한 것 — 판단이 필요했던 지점과 근거
--
--  1. **운영자 열람을 정책으로 연다.** 서비스롤로 우회해 읽으면 경계가 RLS 가 아니라
--     앱 코드가 된다(§5.5). 0019 가 만든 `is_operator()` 를 그대로 쓴다 —
--     0033 이 정산서에, 0031 이 조율 큐에 같은 방식으로 열었다.
--
--  2. **쓰기 정책은 주지 않는다.** 요율은 **정산 금액을 정하는 값**이다. 정책으로 열면
--     "누가 운영자인가" 를 정책이 판정하게 되는데, 요율 한 줄이 모든 업체의 수입을
--     바꾸므로 그 경로는 **서비스롤 + API 권한 판정**으로 좁힌다(0029 서명·0030 결제·
--     0033 정산이 같은 결론에 이르렀다). 정책 없음 = 기본 거부다.
--
--  3. **요율 행을 지우지 않는다.** 과거 계약의 스냅샷은 `bookings`·`contracts` 에
--     박혀 있지만(D-16), **"그때 어떤 요율표가 있었나" 를 재현하는 근거**는 이 표다.
--     지우면 정산 분쟁에서 "이 요율이 어디서 나왔나" 를 답할 수 없다(D-23).
--     그래서 **DELETE 권한을 회수**하고, 끝내는 방법은 `effective_to` 를 닫는 것이다.
--     끝난 요율은 화면에서 '종료' 로 보이고 행은 남는다.
--
--  4. **겹침은 이미 DB 가 막는다**(0006 의 EXCLUDE). 이 파일은 그 위에 아무것도 더하지
--     않는다 — 대신 **화면이 저장 전에 먼저 알려주도록** 순수 함수를 뒀다
--     (`lib/core/pricing/rate-admin.ts`). DB 오류 메시지를 그대로 보여주면 운영자는
--     무엇을 고쳐야 할지 모른다.
--
--  5. **요율 값을 시드하지 않는다.** O-02 는 여전히 미결이고, 값을 마이그레이션에
--     넣으면 그것이 운영 기준처럼 굳는다(0031 이 위약금 가정치에서, 0029 가 조항
--     문안에서 내린 판단과 같다). **로컬 개발용 행은 `seed-accounts.mjs` 가 만든다** —
--     시드 스크립트는 "로컬 데모 데이터" 라는 뜻이 이름에 있고, 운영 값의 출처가
--     아니라는 것이 `seed.sql` 머리말에 이미 적혀 있다.
-- =============================================================================

-- =============================================================================
-- 1) 운영자 열람 (위 근거 1)
-- =============================================================================
create policy commission_rates_select_operator on public.commission_rates
  for select to authenticated
  using (public.is_operator());

comment on policy commission_rates_select_operator on public.commission_rates is
  '운영자는 전 스코프의 요율을 본다(F-A-15). 0006 의 정책은 업체 멤버·플래너용이라 운영자에게는 자기 관리 화면의 목록조차 보이지 않았다. 서비스롤로 우회해 읽지 않는 이유는 경계가 앱 코드가 아니라 RLS 여야 하기 때문이다(§5.5).';

create policy planner_fee_rates_select_operator on public.planner_fee_rates
  for select to authenticated
  using (public.is_operator());

-- =============================================================================
-- 2) 이력 보존 (위 근거 3)
-- -----------------------------------------------------------------------------
-- **쓰기 정책이 없으므로** authenticated 는 어차피 INSERT·UPDATE 를 못 한다. 그런데
-- DELETE 는 정책과 별개로 **권한**이 남아 있어, 나중에 누군가 "운영자 편집" 정책을
-- 붙이는 순간 삭제까지 함께 열린다. 그 때를 대비해 지금 권한을 회수한다 —
-- 0033 이 정산 금액에 대해 한 것과 같은 대비다.
-- =============================================================================
revoke insert, update, delete on public.commission_rates from authenticated, anon;
revoke insert, update, delete on public.planner_fee_rates from authenticated, anon;

comment on table public.commission_rates is
  '업체 수수료 요율(§3.8, F-A-15). 요율 값을 코드·명세에 고정하지 않는다(O-02). **변경은 새 행 추가이고 종료는 effective_to 를 닫는 것이다 — 행을 지우지 않는다.** 지우면 "그때 어떤 요율표가 있었나" 를 재현할 수 없고 그것이 정산 분쟁의 쟁점이다(D-23). 쓰기는 서비스롤 경유(운영자 API)다.';

comment on table public.planner_fee_rates is
  '플래너 수수료 요율(§3.8, F-A-15, D-17). commission_rates 와 같은 규칙 — 값은 코드에 없고, 변경은 새 행, 종료는 effective_to, 삭제는 없다.';

-- =============================================================================
-- 3) 증적 열람 (D-23 · 0019 의 방식)
-- -----------------------------------------------------------------------------
-- **요율 변경은 누가 언제 무엇을 바꿨는지가 곧 분쟁의 근거다.** 운영자만 본다 —
-- 업체에 열면 남의 업체 요율이 이벤트 memo 로 새어 나간다.
-- =============================================================================
create policy entity_events_select_rate on public.entity_events
  for select to authenticated
  using (entity_type in ('commission_rate', 'planner_fee_rate') and public.is_operator());

-- =============================================================================
-- 이 파일이 한 것
--   정책 3 — commission_rates·planner_fee_rates 운영자 SELECT · entity_events 열람
--   GRANT  두 표의 INSERT·UPDATE·DELETE 회수 (쓰기는 서비스롤 경유 · 이력은 지우지 않는다)
--   COMMENT 2 — 변경은 새 행, 종료는 effective_to, 삭제는 없다
--   기존 마이그레이션 수정 없음
--   **요율 값을 시드하지 않았다**(O-02) — 로컬 데모 행은 seed-accounts.mjs 가 만든다.
-- =============================================================================
