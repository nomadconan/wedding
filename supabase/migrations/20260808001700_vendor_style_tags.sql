-- F-C-10 의 필터 다섯 중 **스타일만 저장할 자리가 없었다.** 커플에는
-- `couples.style_tags` 가 있는데(F-C-01 온보딩 5번 문항) 업체에는 대응하는 컬럼이
-- 없어서, 스타일로 거를 수 있는 근거가 DB 에 존재하지 않았다.
--
-- **빈 컬럼만 만들고 필터를 여는 선택지는 버렸다.** 입력 화면이 없으면 값이 영원히
-- 비고, 그러면 어떤 스타일을 골라도 0건이 나온다. 화면은 "그 스타일 업체가 없다" 고
-- 말하지만 사실은 "아무도 적지 않았다" 이다 — 둘은 다른 정보다(S2-08 에서 세운
-- "0건과 아직 측정하지 않음은 다르다" 와 같은 원칙). 그래서 이 마이그레이션과 함께
-- 업체 프로필(S2-02 화면)에 입력 자리를 붙였다.
--
-- **어휘는 커플과 같은 것을 쓴다.** `lib/core/schemas/onboarding.ts` 의 `STYLE_TAGS`
-- 하나다. 업체용 어휘를 따로 두면 "커플이 고른 내추럴" 과 "업체가 적은 내추럴" 이
-- 다른 값이 되어 매칭 자체가 성립하지 않는다.
-- =============================================================================

alter table public.vendors
  add column if not exists style_tags text[] not null default '{}';

comment on column public.vendors.style_tags is
  '업체 스타일(F-C-10 필터). 커플의 couples.style_tags 와 **같은 어휘**를 쓴다 — 값 집합은 lib/core/schemas/onboarding.ts 의 STYLE_TAGS 이며 아래 CHECK 가 강제한다.';

-- 값 집합을 못박는다. 오타 한 번이면 그 업체는 어떤 필터에도 걸리지 않고,
-- 아무도 그 사실을 눈치채지 못한다.
alter table public.vendors
  add constraint vendors_style_tags_chk
  check (
    style_tags <@ array[
      'modern', 'classic', 'natural', 'romantic',
      'minimal', 'luxury', 'outdoor', 'small_wedding'
    ]::text[]
  );

-- 탐색 필터는 배열 겹침(&&)으로 판정한다. GIN 이 그 연산자를 받는다.
create index if not exists idx_vendors_style_tags
  on public.vendors using gin (style_tags);

-- =============================================================================
-- RLS 는 손대지 않는다 (§3.9)
--   `vendors` 정책 그대로다 — active 업체는 anon 도 읽고, 수정은 owner 뿐이다.
--   스타일은 공개 정보이므로 별도 처리가 필요 없다.
-- =============================================================================

