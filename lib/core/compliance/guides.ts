/**
 * 업체용 수정 가이드 (S7-13 · 명세서 §2.3 F-V-10)
 *
 * ── 왜 룰 정의(`detect-rules.ts`)에 넣지 않는가 ─────────────────────────────
 * 검출 룰은 **무엇을 찾는가**이고 여기 있는 것은 **업체가 무엇을 고치면 되는가**다.
 * 같은 룰이 소비자에게는 "이 조항이 불리할 수 있어요" 로, 업체에게는 "이렇게 적으면
 * 걸리지 않아요" 로 읽힌다 — **대상이 다르면 문장이 다르다.** 룰 정의에 섞으면
 * T-04 가 세운 구조와 시드 동기화를 업체 문구 때문에 건드리게 된다.
 *
 * ── 이 문장들이 지켜야 하는 것 ──────────────────────────────────────────────
 *  1. **법률 자문이 아니다**(§7.7 · CLAUDE.md §2.3). "이렇게 하면 적법하다" 가 아니라
 *     **"우리 검사에 걸리지 않으려면 무엇이 명시돼 있어야 하는가"** 를 적는다.
 *  2. **조항 문안을 대신 써 주지 않는다.** 문안을 주면 업체는 그것을 그대로 쓰고,
 *     그 문장의 법적 결과를 우리가 책임지는 모양이 된다(O-03 법무 검수 대기).
 *     **무엇이 담겨야 하는지**까지만 적는다.
 *  3. **조항 번호를 적지 않는다.** `basis_ref` 와 같은 규칙이다 — 지어낸 번호는
 *     사실처럼 읽히고, T-04 가 테스트로 그것을 막아 두었다.
 *
 * 룰이 20종이므로 가이드도 20개다. **하나라도 비면 테스트가 막는다** — 가이드 없는
 * 룰이 걸리면 업체는 "고치라" 는 말만 듣고 무엇을 고칠지 모른다.
 */

