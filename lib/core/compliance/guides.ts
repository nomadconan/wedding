const GUIDE_BY_CODE = new Map(COMPLIANCE_GUIDES.map((guide) => [guide.ruleCode, guide]));

/**
 * 룰 코드 → 가이드.
 *
 * **없으면 던지지 않고 null 이다.** 룰이 늘어난 날 가이드가 늦게 붙을 수 있고, 그때
 * 진단 자체가 500 이 되면 안 된다 — 화면은 가이드 없이 걸린 사실만 보여준다.
 * 다만 **테스트가 20종 전부에 가이드가 있는지 막는다.**
 */
export function guideFor(ruleCode: string): ComplianceGuide | null {
  return GUIDE_BY_CODE.get(ruleCode) ?? null;
}

/** 가이드가 없는 룰 코드. 테스트와 `db:rls` 가 이것이 비어 있는지 본다. */
export function rulesWithoutGuide(): string[] {
  return DETECT_RULES.filter((rule) => !GUIDE_BY_CODE.has(rule.code)).map((rule) => rule.code);
}

