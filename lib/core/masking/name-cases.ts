//
// 둘은 같은 저울의 양 끝이라 **한쪽만 세면 반드시 다른 쪽이 나빠진다.** S7-13 이
// 겪은 것이 그것이다 — `담당 작가 교체가 필요한 경우` 의 "교체가" 가 이름으로 잡혀
// 문장이 지워졌고, 그 결과 **갖춰져 있던 조항이 '없다' 로 판정**됐다(R-15·R-04 부재).
//
// ── 왜 골든셋(FIX-42) 을 기다리지 않았나 ────────────────────────────────────
// FIX-42 가 요구하는 것은 **검출 룰 20종 × 샘플 계약서의 출력 스냅샷**이다. 그것은
// "룰이 무엇을 찾아냈나" 를 고정하는 장치이고, 여기서 물어야 하는 것은 **"마스킹이
// 무엇을 지웠나"** 다. 후자는 순수 함수의 입출력이라 **직접, 더 좁게** 잴 수 있고,
// 스냅샷보다 원인을 정확히 가리킨다. FIX-42 는 여전히 필요하지만(룰·프롬프트 회귀)
// 이 수정의 안전장치로는 이 표가 맞다.
//
// ── 문구는 실제 계약서를 흉내낸다 ───────────────────────────────────────────
// **실제 계약서를 커밋하지 않는다**(CLAUDE.md §5.6). 아래 이름은 전부 지어낸 것이고
// 문장은 표준약관·업체 약관에서 흔한 표현을 본떴다.
// ══════════════════════════════════════════════════════════════════════════

