// 개인정보 마스킹 패턴 정의 (명세서 §5.2 3단계, CLAUDE.md §5.2)
//
// 프레임워크 무관 · 순수 TypeScript. React/Next/DB 를 import 하지 않는다.
//
// 중요
//  * 여기 정의된 패턴은 AI 에 원문을 전달하기 **전에** 적용된다.
//  * 마스킹 맵은 메모리에서만 유지하며 DB·로그·파일에 쓰지 않는다.
//  * 패턴에 g 플래그를 붙이지 않는다(lastIndex 상태 공유로 인한 오탐 방지).
//    반복 치환이 필요한 곳에서 호출부가 g 플래그 사본을 만들어 쓴다.

/** 마스킹 대상 개인정보 종류. */
export type PiiKind =
  | "rrn" // 주민등록번호
  | "biz_no" // 사업자등록번호
  | "phone" // 전화번호(휴대전화·유선)
  | "email" // 이메일
  | "account" // 계좌번호
  | "address" // 주소
  | "name"; // 이름

export const PII_KINDS: readonly PiiKind[] = [
  "rrn",
  "biz_no",
  "phone",
  "email",
  "account",
  "address",
  "name",
] as const;

/**
 * 결정적으로 검출 가능한 종류.
 * 마스킹 후 이 종류의 패턴이 하나라도 남아 있으면 **마스킹 실패**로 판정하고
 * AI 호출을 중단한다(§5.2 3단계 "미검출 위험 패턴 존재 시 중단·경보").
 *
 * 이름·주소는 표기 방식이 자유로워 정규식만으로 완전 검출을 보장할 수 없다.
 * 따라서 차단 판정 대상에서 제외하고 별도 경고로만 다룬다.
 */
export const BLOCKING_PII_KINDS: readonly PiiKind[] = [
  "rrn",
  "biz_no",
  "phone",
  "email",
  "account",
] as const;

/** 마스킹 규칙 하나. */
export type MaskPattern = {
  kind: PiiKind;
  /** 규칙 식별자 — 테스트·경보 메시지에서 어떤 패턴이 걸렸는지 지목하는 용도. */
  id: string;
  /** g 플래그 없이 정의한다. */
  regex: RegExp;
  /**
   * 치환 대상 캡처 그룹 번호. 미지정이면 매치 전체를 치환한다.
   * 예: "신랑 홍길동" 에서 이름만 치환하려면 group 을 지정한다.
   */
  group?: number;
  /** 매치가 이 패턴에도 걸리면 오탐으로 보고 건너뛴다. */
  skipIf?: RegExp;
};

/** 날짜 표기(2026-08-08)를 계좌번호로 오인하지 않기 위한 가드. */
const DATE_LIKE = /^\d{4}\s*-\s*\d{1,2}\s*-\s*\d{1,2}$/;

/**
 * 이름 자리에 오기 쉬운 일반 명사. 이것들이 잡히면 이름이 아니라 오탐이다.
 * (예: "고객님", "담당자 확인", "대표 이사")
 *
 * ── FIX-31 이 여기를 늘렸다 ─────────────────────────────────────────────────
 * S7-13 이 `담당 작가 교체가 필요한 경우` 의 **"교체가"** 가 이름으로 잡혀 문장이
 * 지워지는 것을 봤다. 그 문장은 갖춰져 있던 조항이었고, 지워진 탓에 **'조항 없음'
 * 으로 판정**됐다. 실제로 재 보니 계약서 문구 30개 중 **26개**가 같은 방식으로
 * 망가졌다(`name-cases.ts`).
 *
 * **여기 있는 낱말은 전부 "성씨로 시작하는 계약서 명사"** 다 — 성씨로 시작하지
 * 않는 낱말은 아래 `SURNAME` 검사가 이미 걸러 내므로 적을 필요가 없다.
 * 그래서 이 목록은 무한정 늘지 않는다.
 *
 * **조사를 하나까지 떼고 본다.** 캡처는 이름 전체를 욕심껏 집으므로 `변경이`·
 * `판단으(로)` 처럼 조사가 붙어 들어온다 — 떼지 않으면 이 목록이 아무것도 못
 * 걸러 낸다(실제로 오탐이 26 에서 13 까지만 줄고 멈췄다).
 */
const NON_NAME_WORDS =
  /^(?:고객|손님|사장|신랑|신부|대표|담당|담당자|작가|실장|기사|선생|여러분|본인|당사|귀사|확인|서명|날인|기재|없음|해당|미정|동일|참석|예정|변경|변동|추가|지정|배정|선정|정보|금액|인원|연락|환불|안내|수정|계약|동의|부재|만족|판단|요청|이사|상담|일정|촬영|취소|해지|위약|잔금|계약금|보증|보증금|예약|일시|장소|기간|조항|약관|사유|절차|방법|기준|내용|결과|상태|비용|대금|정산|환급|연장|단축|이행|불이행)(?:[은는이가을를의도만과와에로으])?$/;

/**
 * 한국 성씨. **닫힌 집합**이라 이름 판정의 근거가 된다 (FIX-31).
 *
 * ── 왜 성씨를 요구하는가 ────────────────────────────────────────────────────
 * 라벨 뒤에 오는 2~3자 한글을 전부 이름으로 보면 **계약서 문장이 남아나지 않는다.**
 * 반대로 이름은 거의 예외 없이 **성으로 시작**한다 — 이것이 오탐을 크게 줄이면서
 * 미탐은 거의 늘리지 않는 유일한 구조적 신호다.
 *
 * ── 넓게 깐다 ───────────────────────────────────────────────────────────────
 * **빠진 성씨는 곧 유출**이다(그 사람의 이름이 AI 로 그대로 나간다). 반대로 넣어서
 * 생기는 손해는 오탐 하나이고 그것은 위 `NON_NAME_WORDS` 가 받는다. 저울이 한쪽으로
 * 분명히 기울어 있으므로 **드문 성씨까지 넣는다.**
 *
 * **복성을 먼저 적는다** — 교대(交代)로 긴 것이 먼저 걸려야 `남궁민` 을 `남` + `궁민`
 * 으로 자르지 않는다.
 */
const SURNAME =
  "(?:남궁|황보|제갈|사공|선우|서문|독고|동방|망절|어금|" +
  "김|이|박|최|정|강|조|윤|장|임|한|오|서|신|권|황|안|송|류|유|전|홍|고|문|양|손|배|백|허|" +
  "노|심|하|곽|성|차|주|우|구|민|나|지|엄|채|원|천|방|공|현|함|변|염|여|추|도|소|석|선|설|" +
  "마|길|위|연|표|명|기|반|왕|금|옥|육|인|맹|제|모|남|탁|국|어|은|편|용|예|경|봉|사|부|가|" +
  "복|태|목|계|피|두|감|호|빈|동|온|팽|승|간|상|시|단|견|판|당|화|창|후|야|묘|초|평|삼|" +
  "돈|만|범)";

/** 라벨 뒤 이름 뒤에 붙을 수 있는 조사·경계. "강예린에게" 의 "에게" 를 놓치지 않는다. */
const NAME_BOUNDARY = "(?=[\\s,.)\\]·/]|$|은|는|이|가|을|를|의|도|만|과|와|에|로|으|께|님|씨|귀하)";

/**
 * 적용 순서가 곧 우선순위다.
 * 더 구체적인 패턴(주민번호·사업자번호)을 먼저 소비해야
 * 뒤의 느슨한 패턴(계좌번호)이 같은 문자열을 다시 잡지 않는다.
 */
export const MASK_PATTERNS: readonly MaskPattern[] = [
  // ── 주민등록번호 ──────────────────────────────────────────────
  {
    kind: "rrn",
    id: "rrn.standard",
    regex: /\b\d{6}\s*[-–—]\s*[1-4]\d{6}\b/,
  },

  // ── 사업자등록번호 (3-2-5) ────────────────────────────────────
  {
    kind: "biz_no",
    id: "biz_no.standard",
    regex: /\b\d{3}\s*-\s*\d{2}\s*-\s*\d{5}\b/,
  },

  // ── 전화번호 ──────────────────────────────────────────────────
  {
    kind: "phone",
    id: "phone.mobile",
    regex: /\b01[016789]\s*-?\s*\d{3,4}\s*-?\s*\d{4}\b/,
  },
  {
    kind: "phone",
    id: "phone.landline",
    // 02 / 031~064 지역번호. 하이픈은 필수로 둬서 일반 숫자열 오탐을 막는다.
    regex: /\b0(?:2|[3-6][1-5])\s*-\s*\d{3,4}\s*-\s*\d{4}\b/,
  },
  {
    kind: "phone",
    id: "phone.tollfree",
    regex: /\b1(?:5|6|8)\d{2}\s*-\s*\d{4}\b/,
  },

  // ── 이메일 ────────────────────────────────────────────────────
  {
    kind: "email",
    id: "email.standard",
    regex: /\b[\w.+-]+@[\w-]+(?:\.[\w-]+)+\b/,
  },

  // ── 계좌번호 ──────────────────────────────────────────────────
  {
    kind: "account",
    id: "account.with_bank",
    // 은행명이 앞에 붙은 숫자열. 하이픈 유무를 가리지 않는다.
    regex:
      /(?:국민|신한|우리|하나|농협|기업|산업|수협|씨티|SC제일|카카오뱅크|케이뱅크|토스뱅크|새마을금고|우체국|부산|대구|경남|광주|전북|제주)\s*(?:은행)?\s*(?:계좌)?\s*[:：]?\s*\d[\d\s-]{8,}\d/,
  },
  {
    kind: "account",
    id: "account.generic",
    // 은행명 없이 적힌 계좌번호 형태. 날짜 표기는 skipIf 로 제외한다.
    regex: /\b\d{3,6}\s*-\s*\d{2,6}\s*-\s*\d{4,8}\b/,
    skipIf: DATE_LIKE,
  },

  // ── 주소 ──────────────────────────────────────────────────────
  {
    kind: "address",
    id: "address.korean",
    regex:
      /(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)(?:특별시|광역시|특별자치시|특별자치도|도)?\s*[가-힣]+(?:시|군|구)\s*[가-힣\d]+(?:로|길|동|읍|면)\s*[\d-]*(?:\s*[\d]+층)?(?:\s*[\d]+호)?/,
  },

  // ── 이름 ──────────────────────────────────────────────────────
  // 이름은 문맥 라벨이 있을 때만 잡는다. 라벨 없는 2~4자 한글을 전부 이름으로
  // 보면 일반 명사를 파괴해 계약서 분석 자체가 불가능해진다.
  {
    kind: "name",
    id: "name.labeled",
    // 라벨과 이름 사이의 구분자(공백 또는 콜론)를 필수로 둔다.
    // 구분자를 선택으로 두면 "고객님께" 의 "님께" 를 이름으로 잡는다.
    //
    // **이름은 성으로 시작한다**(FIX-31). 라벨 뒤 2~4자를 전부 이름으로 보던 예전
    // 규칙은 `작가 교체가` 의 "교체가" 를 집어 **문장을 지웠다.** 성씨를 요구하면
    // 그 부류가 대부분 사라지고, 남는 것(`변경`·`추가`처럼 성씨로 시작하는 명사)은
    // `NON_NAME_WORDS` 가 받는다.
    //
    // 뒤 경계에 **조사를 허용한다** — 예전 규칙은 `담당자 강예린에게` 를 아예 못
    // 잡았다(뒤가 공백이 아니라서). 좁히면서 동시에 **놓치던 것을 하나 주웠다.**
    regex: new RegExp(
      "(?:신랑|신부|고객|계약자|의뢰인|대표자|대표|담당자|작가|실장|성명|이름)" +
        "(?:님)?(?:\\s*[:：]\\s*|\\s+)" +
        `(${SURNAME}[가-힣]{1,2})` +
        NAME_BOUNDARY,
    ),
    group: 1,
    skipIf: NON_NAME_WORDS,
  },
  {
    kind: "name",
    id: "name.suffixed",
    // "홍길동 님", "홍길동 씨", "홍길동 귀하", "홍길동 님과", "홍길동 님의"
    // 호칭 뒤에 조사가 붙는 경우가 흔하므로 한 글자 조사까지 허용한다.
    regex: /([가-힣]{2,4})\s*(?:님|씨|귀하)(?:께|[과와은는이가의도만을를에])?(?=\s|$|[,.)\]·/])/,
    group: 1,
    skipIf: NON_NAME_WORDS,
  },
] as const;

/** 차단 판정에 사용할 패턴만 추린 목록. */
export const BLOCKING_MASK_PATTERNS: readonly MaskPattern[] = MASK_PATTERNS.filter((p) =>
  BLOCKING_PII_KINDS.includes(p.kind),
);
