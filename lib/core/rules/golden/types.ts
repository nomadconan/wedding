/** 스캔을 어느 입력에 돌렸는가. **두 경로가 실제로 다르다**(아래 주석). */
export const GOLDEN_PATHS = ["raw", "masked"] as const;
export type GoldenPath = (typeof GOLDEN_PATHS)[number];

/**
 * 왜 경로가 둘인가.
 *
 * 룰 스캔을 부르는 곳이 둘인데 **넣는 것이 서로 다르다.**
 *
 *   `lib/reports/analyze.ts`  (소비자 리포트 · S7-03) → **마스킹본**을 스캔한다.
 *   `lib/compliance/scan.ts`  (업체 자가진단 · S7-13) → **원문**을 스캔하고 인용만 가린다.
 *
 * 그래서 **마스킹 패턴을 건드리면 소비자 리포트의 판정이 함께 움직인다.** FIX-31 이
 * 정확히 그것이었다 — `담당 작가 교체가` 의 "교체가" 가 이름으로 잡혀 문장이 지워졌고
 * **갖춰져 있던 조항이 '없다' 로 뒤집혔다**(R-15·R-04 부재).
 *
 * 그 사고를 다시 잡으려면 **두 경로를 같이 재고, 둘이 갈리는 것 자체를 실패로** 봐야
 * 한다. 한쪽만 재면 마스킹을 좁히다 룰을 깨뜨려도 표는 초록이다.
 */
export const GOLDEN_PATH_LABEL: Record<GoldenPath, string> = {
  raw: "원문 스캔 (업체 자가진단 경로)",
  masked: "마스킹본 스캔 (소비자 리포트 경로)",
};

export type GoldenCaseKind =
  /** 조항 한두 줄. 룰 하나를 정면으로 겨눈다. */
  | "clause"
  /** 계약서 한 통. **잡힌 룰 집합 전체를 스냅샷으로 고정**한다(§7.5 "골든셋 스냅샷 비교"). */
  | "contract";

export type GoldenCase = {
  /** 'G-R01-hit' 처럼 읽어서 무엇을 재는지 알 수 있게. */
  id: string;
  kind: GoldenCaseKind;
  /** 이 케이스가 겨냥한 룰. **커버리지 집계의 축**이다. */
  focus: readonly string[];
  title: string;
  /** 계약서 문구(지어낸 것). */
  text: string;
  /** **반드시 잡혀야 하는** 룰 코드. */
  detected: readonly string[];
  /** **절대 잡히면 안 되는** 룰 코드. */
  notDetected: readonly string[];
  /**
   * `detected` 가 전부인가.
   *
   * `contract` 케이스는 참이다 — 목록에 없는 룰이 하나라도 잡히면 실패한다. 이것이
   * §7.5 가 말하는 **스냅샷 비교**이며, 조항 케이스와 달리 **룰 하나를 넓혔을 때
   * 옆 계약서에서 새로 튀어나오는 오탐**을 잡는다.
   */
  exact: boolean;
  /** 왜 이 케이스를 두는가. 실패했을 때 읽는 사람이 판단할 근거다. */
  note: string;
};

/** 검사 하나의 결과. **통과도 실패도 같은 모양으로 센다** — 분모가 보여야 한다. */
export type GoldenCheck = {
  caseId: string;
  path: GoldenPath;
  kind: "miss" | "false_positive" | "unexpected" | "masking_drift";
  /** 룰 코드. `masking_drift` 는 갈린 코드들을 쉼표로 잇는다. */
  target: string;
  ok: boolean;
  /** 실패했을 때 사람이 읽는 한 줄. 통과면 빈 문자열이다. */
  detail: string;
};
