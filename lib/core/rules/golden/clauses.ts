// 조항 단위 골든 케이스 — 룰 20종 × (잡히는 것 · 안 잡히는 것) (FIX-42)
//
// 룰 하나를 정면으로 겨눈다. **한 룰에 최소 두 개** — 잡혀야 하는 문장 하나와
// 잡히면 안 되는 문장 하나다. 후자가 없으면 "정규식을 `/./` 로 바꿔도 통과하는 표"가
// 되고, 그 표는 아무것도 지키지 않는다.
//
// ── 경계 케이스를 고른 기준 ─────────────────────────────────────────────────
// **한 글자 차이로 갈리는 자리**를 고른다. 49% ↔ 50%(R-01), `협의 후 변경` ↔
// `일방 변경`(R-09), `아래 별표에 명시` ↔ `별도 비용`(R-05), `철회할 수 있다` ↔
// `철회할 수 없다`(R-18) 처럼 **선의의 조항과 독소 조항이 스치는 곳**이다.
//
// 문구·이름·번호는 전부 지어낸 것이다(CLAUDE.md §5.6).

import type { GoldenCase } from "./types";

type ClauseInput = {
  id: string;
  focus: readonly string[];
  title: string;
  text: string;
  detected?: readonly string[];
  notDetected?: readonly string[];
  note: string;
};

/** 조항 케이스는 **스냅샷이 아니다** — 겨냥한 룰만 본다(`exact: false`). */
function clause(input: ClauseInput): GoldenCase {
  return {
    id: input.id,
    kind: "clause",
    focus: input.focus,
    title: input.title,
    text: input.text,
    detected: input.detected ?? [],
    notDetected: input.notDetected ?? [],
    exact: false,
    note: input.note,
  };
}

