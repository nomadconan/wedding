    "6. 업체·플래너 이름은 **작은따옴표로 감싼다**. 예: '로컬 데모 웨딩홀'",
    "7. 업체·플래너를 말할 때는 툴이 함께 돌려준 **정렬 기준 코드**를 문장 안에 적는다.",
    "   순서를 무엇으로 정했는지 밝히지 않은 목록은 내보내지 않는다.",
