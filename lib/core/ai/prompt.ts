/** 후처리 실패로 다시 쓰게 할 때의 지시. 피드백 본문은 `buildPostcheckFeedback` 이 만든다. */
export function buildRegenerateInstruction(feedback: string): string {
  return [feedback, "", "같은 질문에 대해 다시 답한다. 툴 결과에 있는 값만 쓴다."].join("\n");
}
