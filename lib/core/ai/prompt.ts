import { AI_DISCLAIMER } from "../legal";

import { EMPTY_GUIDANCE, EMPTY_REASONS } from "./empty";
import { IRREVERSIBLE_ACTIONS, type ToolSpec } from "./tools";

/**
 * 플래너 시스템 프롬프트 (S7-20 · 명세서 §5.6 가드레일)
 *
 * **프롬프트는 코드로 관리하고 판본을 붙인다**(CLAUDE.md §8). 결과가 달라졌을 때
 * 모델이 바뀐 것인지 문구가 바뀐 것인지 구분할 수 있어야 하고, 그 판본은
 * `ai_call_logs.prompt_version` 에 남는다.
 *
 * **프롬프트가 후처리를 성립시킨다.** 여기서 요구하는 두 가지 표기 규칙 — 숫자는
 * 아라비아 숫자로, 이름은 작은따옴표로 — 이 없으면 `postcheck` 가 검사할 형태가
 * 없어진다. 문구를 고칠 때 그 둘을 빼지 않는다.
 *
 * **프롬프트는 경계가 아니다.** 여기 적힌 금지는 모델이 지키기를 바라는 것이고,
 * 실제로 막는 것은 툴 목록(없는 툴은 부를 수 없다) · 후처리(없는 값은 나갈 수 없다) ·
 * RLS(남의 데이터는 읽을 수 없다)다.
 */

export const PLANNER_PROMPT_VERSION = "planner@1";

/** 툴 목록을 프롬프트에 적어 넣는다 — 모델이 무엇을 부를 수 있는지 한 번 더 못 박는다. */
function toolLines(tools: readonly ToolSpec[]): string[] {
  return tools.map((tool) => `- ${tool.name}: ${tool.summary}`);
}

